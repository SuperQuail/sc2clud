-- 0059_clean_doc_citations：清掉权限点描述里的设计文档引注（「v2 §21.2」这类）。
--
-- 0017 的 topic.pin 描述是「置顶 / 精华（两个端点共用这一个权限点，v2 §21.2）」，
-- 这条会原样出现在后台角色矩阵屏的权限点说明列里 —— 设计稿编号对管理员没有任何用。
--
-- 为什么还要这条新迁移：已经迁移过的库（dev / 未来的 prod）不会重跑 0017，只改它等于没改。
-- 0017 里的字面量也一并清掉，让新库在第一次迁移后就干净（两边收敛到同一个值）。
--
-- 幂等 + 不覆盖后台调整：只在值**逐字等于**带引注的旧串时替换，重跑第二次 0 行；
-- 管理员在后台改过这条描述（0017 的「重跑不覆盖」纪律）就不匹配，一个字也不动。
UPDATE permissions
   SET description = '置顶 / 精华（两个端点共用这一个权限点）'
 WHERE key = 'topic.pin'
   AND description = '置顶 / 精华（两个端点共用这一个权限点，v2 §21.2）';
