// 画布与字形尺寸（d5-content §7.1 的 80×28 放大到前端实际要的展示尺寸：
// ProductCaptcha 的 img 是 40px 高、min-width 7.5rem，80×28 会糊）。
const (
	width  = 120
	height = 40
	scale  = 4 // 5×7 点阵放大 4 倍 = 20×28，画布里有上下抖动的余量
)

// renderPNG 把 answer（4 个 alphabet 里的字符）画成 PNG。
// rnd 由调用方给：测试要可复现的图，生产用 rand.New(rand.NewSource(crypto 随机种子))。
func renderPNG(answer string, rnd *rand.Rand) ([]byte, error) {
	img := image.NewRGBA(image.Rect(0, 0, width, height))
	bg := color.RGBA{R: 0xF7, G: 0xF8, B: 0xFA, A: 0xFF}
	fg := color.RGBA{R: 0x1F, G: 0x2A, B: 0x37, A: 0xFF}
	noise := color.RGBA{R: 0xB6, G: 0xC2, B: 0xCF, A: 0xFF}
	fill(img, bg)

	// 每个字符占 26px，5×7 放大 4 倍是 20×28：留 6px 间距，肉眼分得开。
	const cell = 26
	const glyphW, glyphH = 5 * scale, 7 * scale
	for i := 0; i < len(answer); i++ {
		g, ok := glyphOf(answer[i])
		if !ok {
			return nil, fmt.Errorf("captcha: 字形表里没有 %q", answer[i])
		}
		x0 := 9 + i*cell + rnd.Intn(3) - 1
		y0 := (height-glyphH)/2 + rnd.Intn(5) - 2 // ±2px 纵向抖动
		drawGlyph(img, g, x0, y0, fg)
	}
	// 噪点：均匀撒 40 个浅灰点。**不画干扰线** —— 线会穿过字形，5×7 点阵本来笔画就细。
	for i := 0; i < 40; i++ {
		img.Set(rnd.Intn(width), rnd.Intn(height), noise)
	}

	var buf bytes.Buffer
	if err := png.Encode(&buf, img); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

func fill(img *image.RGBA, c color.RGBA) {
	for y := 0; y < height; y++ {
		for x := 0; x < width; x++ {
			img.Set(x, y, c)
		}
	}
}

// glyphOf 把字符映射到字形。查表前统一大写：答案大小写不敏感（d5-content §7.1）。
func glyphOf(ch byte) ([7]byte, bool) {
	if ch >= 'a' && ch <= 'z' {
		ch -= 'a' - 'A'
	}
	i := strings.IndexByte(alphabet, ch)
	if i < 0 {
		return [7]byte{}, false
	}
	return glyph[i], true
}

// drawGlyph 按位画：每个点阵位画成 scale×scale 的方块，整行再加一点水平偏移（「轻微扭曲」）。
func drawGlyph(img *image.RGBA, g [7]byte, x0, y0 int, c color.RGBA) {
	for row := 0; row < 7; row++ {
		bits := g[row]
		dx := x0 + row/3 // 逐行递进 1px：看起来像斜体，不引仿射变换
		for col := 0; col < 5; col++ {
			if bits&(1<<uint(4-col)) == 0 {
				continue
			}
			for sy := 0; sy < scale; sy++ {
				for sx := 0; sx < scale; sx++ {
					px, py := dx+col*scale+sx, y0+row*scale+sy
					if px >= 0 && px < width && py >= 0 && py < height {
						img.Set(px, py, c)
					}
				}
			}
		}
	}
}

